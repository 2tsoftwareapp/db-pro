use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Schema {
    pub name: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Table {
    pub name: String,
    pub schema: String,
    pub row_count: Option<u64>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Column {
    pub name: String,
    pub data_type: String,
    #[serde(default)]
    pub ordinal: usize,
    pub nullable: bool,
    pub default: Option<String>,
    pub is_primary_key: bool,
    #[serde(default)]
    pub is_unique: bool,
    #[serde(default)]
    pub is_identity: bool,
    #[serde(default)]
    pub is_generated: bool,
    #[serde(default)]
    pub collation: Option<String>,
    /// Enum labels for enum-typed columns; empty for all other types.
    #[serde(default)]
    pub enum_labels: Vec<String>,
    pub table_name: String,
    pub schema: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PrimaryKey {
    pub constraint_name: String,
    pub columns: Vec<String>,
    pub table_name: String,
    pub schema: String,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IndexOrigin {
    #[default]
    User,
    UniqueConstraint,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Index {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
    #[serde(default)]
    pub method: String,
    #[serde(default)]
    pub primary: bool,
    #[serde(default)]
    pub include_columns: Vec<String>,
    #[serde(default)]
    pub predicate: Option<String>,
    #[serde(default)]
    pub definition: String,
    /// Whether the index is generated by a table-level UNIQUE constraint.
    /// Primary-key autoindexes are omitted from introspection because the
    /// primary-key definition already reproduces them.
    #[serde(default)]
    pub origin: IndexOrigin,
    pub table_name: String,
    pub schema: String,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ForeignKey {
    pub name: String,
    pub from_table: String,
    pub from_columns: Vec<String>,
    pub to_table: String,
    pub to_columns: Vec<String>,
    pub schema: String,
    pub to_schema: String,
    #[serde(default)]
    pub on_update: String,
    #[serde(default)]
    pub on_delete: String,
    #[serde(default)]
    pub match_option: String,
    #[serde(default)]
    pub deferrable: bool,
    #[serde(default)]
    pub initially_deferred: bool,
}

/// What a relation in the `views` list actually is.
///
/// `information_schema.views` cannot describe the whole family: a materialized
/// view (`relkind = 'm'`) and a foreign table (`relkind = 'f'`) are absent from
/// it entirely, and an ordinary view is the only kind it reports. The kind has
/// to travel with the entry so a DDL/clone path emits `CREATE MATERIALIZED VIEW`
/// rather than a plain `CREATE VIEW` (#595).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RelationKind {
    /// A plain SQL view (`relkind = 'v'`, `table_type = 'VIEW'`).
    #[default]
    View,
    /// A materialized view (`relkind = 'm'`, PostgreSQL).
    MaterializedView,
    /// A foreign table (`relkind = 'f'`, PostgreSQL FDW).
    ForeignTable,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct View {
    pub name: String,
    pub schema: String,
    pub definition: String,
    /// `View` unless the provider reports a materialized view or foreign table.
    #[serde(default)]
    pub kind: RelationKind,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Trigger {
    pub name: String,
    pub table_name: String,
    pub schema: String,
    pub timing: String,
    pub event: String,
    pub definition: String,
    /// PostgreSQL trigger function body (CREATE FUNCTION ...); empty for SQLite.
    #[serde(default)]
    pub function_def: String,
    pub enabled: bool,
}

impl Trigger {
    /// Whether `definition` is the provider's authoritative `CREATE TRIGGER`
    /// text rather than the action (`EXECUTE FUNCTION …`) alone.
    ///
    /// Consumers replay a complete definition byte for byte; a summary-only
    /// definition has to be rebuilt, and rebuilding is lossy (#594).
    pub fn is_complete_definition(&self) -> bool {
        self.definition.trim_start().to_ascii_uppercase().starts_with("CREATE TRIGGER")
            || self.definition.trim_start().to_ascii_uppercase().starts_with("CREATE CONSTRAINT TRIGGER")
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RoutineParameter {
    pub name: String,
    pub data_type: String,
    /// IN / OUT / INOUT / VARIADIC / TABLE
    #[serde(default)]
    pub mode: String,
    #[serde(default)]
    pub has_default: bool,
    #[serde(default)]
    pub default_expr: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Function {
    pub name: String,
    #[serde(default)]
    pub schema: String,
    pub routine_type: String,
    pub data_type: String,
    #[serde(default)]
    pub definition: String,
    /// Stable overload identity from `pg_get_function_identity_arguments`.
    #[serde(default)]
    pub identity_arguments: String,
    #[serde(default)]
    pub language: String,
    #[serde(default)]
    pub volatility: String,
    #[serde(default)]
    pub security_definer: bool,
    #[serde(default)]
    pub parameters: Vec<RoutineParameter>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CheckConstraint {
    pub name: String,
    pub table_name: String,
    pub schema: String,
    pub definition: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntrospectResult {
    pub schemas: Vec<Schema>,
    pub tables: Vec<Table>,
    pub columns: Vec<Column>,
    pub primary_keys: Vec<PrimaryKey>,
    pub indexes: Vec<Index>,
    pub foreign_keys: Vec<ForeignKey>,
    pub check_constraints: Vec<CheckConstraint>,
    pub views: Vec<View>,
    pub triggers: Vec<Trigger>,
    pub functions: Vec<Function>,
    /// The provider's own `CREATE TABLE` text, where the provider stores one
    /// (SQLite: `sqlite_master.sql`, verbatim). A table with an entry here is
    /// reproduced byte for byte; rebuilding it from column metadata loses
    /// `AUTOINCREMENT`, `COLLATE`, `WITHOUT ROWID`, `STRICT`, `ON CONFLICT` and
    /// generated-column syntax (#596).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub table_definition_sql: Vec<TableDefinitionSql>,
}

/// One provider-stored `CREATE TABLE` statement.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TableDefinitionSql {
    pub schema: String,
    pub table_name: String,
    pub sql: String,
}

impl IntrospectResult {
    pub fn empty() -> Self {
        Self {
            schemas: Vec::new(),
            tables: Vec::new(),
            columns: Vec::new(),
            primary_keys: Vec::new(),
            indexes: Vec::new(),
            foreign_keys: Vec::new(),
            check_constraints: Vec::new(),
            views: Vec::new(),
            triggers: Vec::new(),
            functions: Vec::new(),
            table_definition_sql: Vec::new(),
        }
    }

    /// The provider-stored `CREATE TABLE` text for one table, if there is one.
    pub fn stored_table_definition(&self, schema: &str, table_name: &str) -> Option<&str> {
        self.table_definition_sql
            .iter()
            .find(|entry| entry.schema == schema && entry.table_name == table_name)
            .map(|entry| entry.sql.as_str())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum DependencyDirection {
    DependsOn,
    DependedBy,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum DependencyKind {
    Table,
    View,
    ForeignKey,
    Trigger,
    Function,
    Sequence,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct TableDependency {
    pub name: String,
    pub schema: String,
    pub kind: DependencyKind,
    pub direction: DependencyDirection,
    pub details: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TableInfo {
    pub table: Table,
    pub columns: Vec<Column>,
    pub primary_key: Option<PrimaryKey>,
    pub indexes: Vec<Index>,
    pub foreign_keys: Vec<ForeignKey>,
    #[serde(default)]
    pub check_constraints: Vec<CheckConstraint>,
    #[serde(default)]
    pub dependencies: Vec<TableDependency>,
}
